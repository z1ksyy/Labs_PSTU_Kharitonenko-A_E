#include <iostream>
#include <clocale>

using namespace std;

int main() 
{
    setlocale(LC_ALL, ".UTF-8");
    const int MAX_N = 100;
    int a[MAX_N];
    int n; // Текущая реальная длина массива
    int k; // Индекс K

    // Ввод исходных данных
    cout << "Введите длину массива (не более 100): ";
    cin >> n;

    cout << "Введите " << n << " элементов массива: ";
    for (int i = 0; i < n; i++) 
    {
        cin >> a[i];
    }

    cout << "Введите индекс K (от 0 до " << n - 1 << "): ";
    cin >> k;
    cout << endl;

    cout << "Исходный массив: ";
    for (int i = 0; i < n; i++) 
        cout << a[i] << " ";
    cout << endl;

    // Распечатать по кольцу влево от K до K-1
    // Движение влево: индекс уменьшается. Если уходит в минус, перескакиваем в конец (n-1)
    cout << "Вывод по кольцу влево (от K до K-1): ";
    int current = k;
    for (int count = 0; count < n; count++) 
    {
        cout << a[current] << " ";
        current--;
        if (current < 0) 
        {
            current = n - 1; // Переход от первого к последнему
        }
    }
    cout << endl;

    // Добавить в кольцо первый и 3 последних элемента
    // Сначала нужно сдвинуть элементы вправо, чтобы освободить место в начале
    if (n + 4 <= MAX_N) 
    {
        // Сдвигаем весь массив на 4 позиции вправо
        for (int i = n - 1; i >= 0; i--) {
            a[i + 4] = a[i];
        }
        
        // Записываем 4 новых элемента в начало
        a[0] = a[4]; // Первый элемент исходного массива
        a[1] = a[n + 3]; // Третий с конца (n-3)
        a[2] = a[n + 2]; // Второй с конца (n-2)
        a[3] = a[n + 1]; // Последний с конца (n-1)
        
        n = n + 4; // Обновляем длину
        k = k + 4; // Индекс K сдвигается, так как начало массива сместилось
        
        cout << "Массив после добавления: ";
        for (int i = 0; i < n; i++) 
            cout << a[i] << " ";
        cout << endl;
    } else 
    {
        cout << "Ошибка. Недостаточно места в массиве для добавления." << endl;
    }

    // Распечатать по кольцу вправо от K до K+1
    // Движение вправо: индекс увеличивается. Если доходит до n, перескакиваем в 0
    cout << "Вывод по кольцу вправо (от K до K+1): ";
    current = k;
    for (int count = 0; count < n; count++) 
    {
        cout << a[current] << " ";
        current++;
        if (current >= n) 
        {
            current = 0; // Переход от последнего к первому
        }
    }
    cout << endl;
    return 0;
}
